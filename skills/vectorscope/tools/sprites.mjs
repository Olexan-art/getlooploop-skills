// Turns assets/*.webp into scripts/lib/sprites.mjs: the two decorations the HTML report carries
// inline, because the report makes no network requests (its CSP allows images from data: only).
// Run after changing an asset: `node tools/sprites.mjs`. tests/sprites.test.mjs fails if the
// module and the assets disagree.
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const root = new URL("../", import.meta.url);

export function spritesModule() {
  const uri = (name) =>
    `data:image/webp;base64,${readFileSync(new URL(`assets/${name}.webp`, root)).toString("base64")}`;
  return [
    "// Generated by tools/sprites.mjs from assets/*.webp. Do not edit by hand.",
    "/** A cross-stitch border, drawn almost invisibly under the report's header and over its footer. */",
    `export const ORNAMENT = ${JSON.stringify(uri("ornament"))};`,
    "/** A motanka, the footer's mark. */",
    `export const MOTANKA = ${JSON.stringify(uri("motanka"))};`,
    "",
  ].join("\n");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(new URL("scripts/lib/sprites.mjs", root), spritesModule());
  console.log("wrote scripts/lib/sprites.mjs");
}
