// Turns assets/brand/getlooploop-mark.webp into scripts/lib/brandmark.mjs: the GetLoopLoop mark,
// inline, because the report makes no network requests (its CSP allows images from data: only).
// The assets are the real logo, the split-signal mark in its two blues (frontend/public/brand/
// split-signal.png for dark surfaces, split-signal-light.png for light ones, in the GetLoopLoop
// repo), downscaled to 112 px wide. Run after changing the asset:
// `node tools/brandmark.mjs`. tests/sprites.test.mjs fails if the module and the asset disagree.
// The AI Search Audit skills vendor this module, so the mark is drawn from one file everywhere.
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const root = new URL("../", import.meta.url);
export const MARK_FILE = "assets/brand/getlooploop-mark.webp";
export const MARK_LIGHT_FILE = "assets/brand/getlooploop-mark-light.webp";

export function brandmarkModule() {
  const uri = (file) => `data:image/webp;base64,${readFileSync(new URL(file, root)).toString("base64")}`;
  return [
    "// Generated by tools/brandmark.mjs from assets/brand/getlooploop-mark*.webp. Do not edit by hand.",
    "/** The GetLoopLoop mark (split signal) for dark surfaces, #4d7dff, as a data URI, 112 by 59 pixels. */",
    `export const GLL_MARK = ${JSON.stringify(uri(MARK_FILE))};`,
    "/** The same mark for light surfaces, #14468f (the site's light-theme accent). */",
    `export const GLL_MARK_LIGHT = ${JSON.stringify(uri(MARK_LIGHT_FILE))};`,
    "",
  ].join("\n");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(new URL("scripts/lib/brandmark.mjs", root), brandmarkModule());
  console.log("wrote scripts/lib/brandmark.mjs");
}
