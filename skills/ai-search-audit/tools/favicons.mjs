// Turns assets/favicons/* into scripts/lib/favicons.mjs: the crawler vendors' favicons, inline,
// because the report makes no network requests (its CSP allows images from data: only).
// They identify which company runs each crawler in the bot grid, at 16 px, and nothing else;
// the marks belong to their owners (see assets/favicons/NOTICE.txt).
// Run after changing an asset: `node tools/favicons.mjs`. tests/assets.test.mjs fails if the
// module and the assets disagree.
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const root = new URL("../", import.meta.url);

export const VENDOR_FILES = [
  ["OpenAI", "openai.com.png", "image/png"],
  ["Anthropic", "anthropic.com.png", "image/png"],
  ["Perplexity", "perplexity.ai.png", "image/png"],
  ["Google", "google.com.png", "image/png"],
  ["Microsoft", "bing.com.png", "image/png"],
  ["Common Crawl", "commoncrawl.org.jpg", "image/jpeg"],
];

export function faviconsModule() {
  const entries = VENDOR_FILES.map(([vendor, file, type]) => `  ${JSON.stringify(vendor)}: ${JSON.stringify(`data:${type};base64,${readFileSync(new URL(`assets/favicons/${file}`, root)).toString("base64")}`)},`);
  return [
    "// Generated by tools/favicons.mjs from assets/favicons/. Do not edit by hand.",
    "/** Each crawler vendor's favicon as a data URI, keyed by the vendor name robots.mjs uses. */",
    "export const FAVICONS = {",
    ...entries,
    "};",
    "",
  ].join("\n");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(new URL("scripts/lib/favicons.mjs", root), faviconsModule());
  console.log("wrote scripts/lib/favicons.mjs");
}
